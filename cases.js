window.HospitalCulpritPhoto = item => {
  const person = window.HospitalCast.find(entry => entry.id === item.culprit);
  const {index, columns, rows, sheet} = person.portrait, column = index % columns, row = Math.floor(index / columns);
  const figure = document.createElement('figure'), frame = document.createElement('span'), photo = document.createElement('img'), stamp = document.createElement('span'), name = document.createElement('figcaption');
  figure.className = 'culprit-photo'; frame.className = 'person-portrait'; stamp.className = 'culprit-stamp';
  figure.setAttribute('aria-label', 'Culpado: ' + person.name); stamp.setAttribute('aria-hidden', 'true');
  photo.src = sheet; photo.alt = 'Retrato de ' + person.name; photo.loading = 'lazy'; photo.draggable = false;
  photo.setAttribute('style', `width:${columns * 100}%;transform:translate(${-column * 100 / columns}%, ${-row * 100 / rows - 1.3}%)`);
  stamp.textContent = 'CULPADO'; name.textContent = person.name;
  frame.append(photo); figure.append(frame, stamp, name);
  return figure;
};

