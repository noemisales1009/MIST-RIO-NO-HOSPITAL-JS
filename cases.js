  const zoom = variant.zoom, panX = (760 - 760 / zoom) * variant.pan, panY = 400 - 400 / zoom, sx = (item.sceneFocus.x - panX) * zoom;
  const x = Math.round(variant.flip ? 760 - sx : sx), y = Math.round((item.sceneFocus.y - panY) * zoom);
  return {label: item.sceneFocus.label, x: Math.max(100, Math.min(660, x)), y: Math.max(80, Math.min(230, y))};
